source_channels = ['LinkedIn', 'Wuzzuf', 'Bayt', 'Referral', 'Agency', 'Company Website']
rec_rows = []
req_id = 1

for dept_id in range(1, 7):
    num_reqs = random.randint(15, 25)
    for _ in range(num_reqs):
        job_id     = random.choice(dept_jobs[dept_id])
        # 20% of requisitions are recent and still Open
        is_open = random.random() < 0.20

        if is_open:
            open_date  = rand_date(date(2024, 6, 1), date(2024, 10, 1))
            status     = 'Open'
            # Still give open reqs a realistic expected close date
            # Engineering open reqs take longer
            if dept_id == 1:
                days_open = random.randint(60, 90)
            elif dept_id == 3:  # HR fills fast
                days_open = random.randint(10, 25)
            else:
                days_open = random.randint(20, 45)
            close_date = open_date + timedelta(days=days_open)
        else:
            open_date  = rand_date(date(2020, 1, 1), date(2024, 5, 1))
            status     = 'Closed'
            # Plant problem: Engineering takes longest to fill
            if dept_id == 1:
                days_open = random.randint(60, 95)
            elif dept_id == 3:  # HR fills fastest
                days_open = random.randint(10, 25)
            elif dept_id == 4:  # Finance moderate
                days_open = random.randint(20, 40)
            else:
                days_open = random.randint(15, 45)
            close_date = open_date + timedelta(days=days_open)

        positions  = random.choices([1, 2, 3], weights=[70, 20, 10])[0]
        filled     = 0 if is_open else positions

        channel    = random.choice(source_channels)
        mgr_id     = dept_manager_map[dept_id]
        recruiter  = dept_manager_map[3]
        close_val  = 'NULL' if is_open else fmt(close_date)

        rec_rows.append(
            f"({req_id}, {job_id}, {dept_id}, {fmt(open_date)}, {close_val}, "
            f"'{status}', {mgr_id}, {recruiter}, {positions}, {filled}, '{channel}')"
        )
        req_id += 1

total_reqs = req_id - 1

