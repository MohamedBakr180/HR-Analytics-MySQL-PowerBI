# 3. EMPLOYEES (1,000 rows)
# ─────────────────────────────────────────────

# Department → job mapping
dept_jobs = {
    1: [1, 2, 12],   # Engineering
    2: [3, 4],        # Sales
    3: [5, 6],        # HR
    4: [7, 8],        # Finance
    5: [9, 10],       # Marketing
    6: [11],          # Support
}

# Department size distribution (totals 1000)
dept_sizes = {1: 280, 2: 200, 3: 80, 4: 120, 5: 150, 6: 170}

# Cities by department
dept_cities = {
    1: 'Cairo', 2: 'Cairo', 3: 'Alexandria',
    4: 'Cairo', 5: 'Giza',  6: 'Alexandria'
}

# Employment types
emp_types = ['Full-time', 'Full-time', 'Full-time', 'Part-time', 'Contract']

# --- Build employee pool ---
employees = []
emp_id = 1

# We'll assign managers after building the pool
# First pass: assign dept, job, hire_date, gender, status

for dept_id, count in dept_sizes.items():
    for i in range(count):
        gender = random.choices(['Male', 'Female'], weights=[55, 45])[0]

        # Plant problem: Engineering has younger/less tenured employees (higher attrition)
        if dept_id == 1:
            hire_start = date(2020, 1, 1)
            hire_end   = date(2024, 6, 1)
        else:
            hire_start = date(2019, 1, 1)
            hire_end   = date(2024, 6, 1)

        hire_date  = rand_date(hire_start, hire_end)
        birth_date = hire_date - timedelta(days=random.randint(365*22, 365*45))

        job_id = random.choice(dept_jobs[dept_id])

        # Manager jobs are rare (1 per dept roughly)
        manager_job_ids = [4, 6, 8, 10, 12]
        if job_id in manager_job_ids and i > 0:
            job_id = dept_jobs[dept_id][0]  # bump back to non-manager

        emp_type = random.choices(emp_types, weights=[60,10,10,10,10])[0]

        # Status: most active, some terminated (will link to attrition later)
        # Engineering has higher termination rate (planted problem)
        if dept_id == 1:
            status = random.choices(['Active', 'Terminated'], weights=[78, 22])[0]
        elif dept_id == 6:
            status = random.choices(['Active', 'Terminated'], weights=[85, 15])[0]
        else:
            status = random.choices(['Active', 'Terminated'], weights=[92, 8])[0]

        employees.append({
            'employee_id':     emp_id,
            'first_name':      fake.first_name_male() if gender == 'Male' else fake.first_name_female(),
            'last_name':       fake.last_name(),
            'gender':          gender,
            'birth_date':      birth_date,
            'hire_date':       hire_date,
            'email':           f"emp{emp_id}@talentbridge.com",
            'phone':           fake.numerify('+20 1## ### ####'),
            'department_id':   dept_id,
            'job_id':          job_id,
            'manager_id':      None,  # assigned below
            'employment_type': emp_type,
            'status':          status,
            'country':         'Egypt',
            'city':            dept_cities[dept_id],
        })
        emp_id += 1

# Assign managers: first employee per dept becomes the manager
dept_manager_map = {}
for e in employees:
    d = e['department_id']
    if d not in dept_manager_map:
        dept_manager_map[d] = e['employee_id']
        e['job_id'] = dept_jobs[d][-1]  # manager job

# Plant problem: one bad manager in Engineering (manager_id = dept_manager_map[1])
# Their team will have extra attrition planted later
bad_manager_id = dept_manager_map[1]

# Assign manager_id to all non-manager employees
for e in employees:
    if e['employee_id'] != dept_manager_map[e['department_id']]:
        e['manager_id'] = dept_manager_map[e['department_id']]

