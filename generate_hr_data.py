# 4. SALARIES
# ─────────────────────────────────────────────

# Job salary base ranges
job_salary_map = {j[0]: (j[2], j[3]) for j in jobs}

sql("-- ------------------------------------------------------------")
sql("-- SALARIES (~1,400 rows — some employees have raise history)")
sql("-- ------------------------------------------------------------")

salary_rows = []
salary_id = 1

for e in employees:
    min_s, max_s = job_salary_map[e['job_id']]

    # Plant problem: female employees earn 8–12% less on average
    gender_factor = random.uniform(0.88, 0.95) if e['gender'] == 'Female' else 1.0

    base_salary = round(random.uniform(min_s, max_s) * gender_factor, 2)
    start = e['hire_date']

    # Plant problem: salary compression — long-tenured employees get fewer raises
    years_employed = (date(2024, 12, 31) - e['hire_date']).days / 365
    if years_employed > 3:
        num_raises = random.choices([0, 1], weights=[40, 60])[0]  # compression
    else:
        num_raises = random.choices([0, 1, 2], weights=[50, 35, 15])[0]

    if num_raises == 0:
        # Single salary record, still active
        end = 'NULL'
        salary_rows.append(
            f"({e['employee_id']}, {base_salary}, {fmt(start)}, {end}, 'Monthly', 'USD')"
        )
    else:
        # Multiple salary records — raise history
        current_salary = base_salary
        current_start  = start
        for r in range(num_raises):
            raise_date = current_start + timedelta(days=random.randint(365, 730))
            if raise_date >= date(2024, 12, 31):
                break
            salary_rows.append(
                f"({e['employee_id']}, {current_salary}, {fmt(current_start)}, {fmt(raise_date - timedelta(days=1))}, 'Monthly', 'USD')"
            )
            # Raise amount: 5–15%
            current_salary = round(current_salary * random.uniform(1.05, 1.15), 2)
            current_start  = raise_date

        # Final (current) salary
        salary_rows.append(
            f"({e['employee_id']}, {current_salary}, {fmt(current_start)}, NULL, 'Monthly', 'USD')"
        )

chunk_insert(
    "INSERT INTO salaries (employee_id, salary_amount, effective_date, end_date, salary_type, currency) VALUES",
    salary_rows
)

